function report=analyze_attitude_eskf(folder)
here=fileparts(mfilename('fullpath'));root=fileparts(fileparts(here));
replays=fullfile(root,'esp32/lqi_firmware/results/attitude_eskf');
out=fullfile(here,'results/attitude_eskf');if ~isfolder(out),mkdir(out);end
names={'原欧拉互补','四元数互补','四元数KF，仅重力','四元数KF＋30s静止偏置学习'};
static=readtable(fullfile(replays,'static_world.csv'));synthetic=readtable(fullfile(replays,'synthetic_world.csv'));
static_report=jsondecode(fileread(fullfile(replays,'static_world.json')));
synthetic_report=jsondecode(fileread(fullfile(replays,'synthetic_world.json')));
a=readtable(fullfile(folder,'attitude.csv'),'TextType','string');
capture=jsondecode(fileread(fullfile(folder,'capture.json')));
t=(double(a.time_us)-double(a.time_us(1)))*1e-6;
heading=@(x,y,z)unwrap(z+atan2(-sin(y).*sin(x),cos(x)));
h0=heading(a.legacy_roll,a.legacy_pitch,a.legacy_yaw);h1=heading(a.roll,a.pitch,a.yaw);
training=a.confirmed_rest~=0;first=find(~training & t>max(t(training))+1,1);mask=(1:height(a))'>=first;
h0=(h0-h0(first))*180/pi;h1=(h1-h1(first))*180/pi;
norm_error=abs(sum([a.qw a.qx a.qy a.qz].^2,2)-1);
native_dt=diff(double(a.time_us));
live=struct('source',folder,'image_sha256',capture.image_sha256,'samples',height(a),'duration_s',t(end),'free_heading_duration_s',t(end)-t(first),...
 'legacy_yaw_final_deg',h0(end),'kf_yaw_final_deg',h1(end),...
 'legacy_yaw_rms_deg',rms(h0(mask)),'kf_yaw_rms_deg',rms(h1(mask)),...
 'legacy_tilt_std_deg',std([a.legacy_roll(mask) a.legacy_pitch(mask)])*180/pi,...
 'kf_tilt_std_deg',std([a.roll(mask) a.pitch(mask)])*180/pi,...
 'mean_update_Hz',(double(a.sequence(end))-double(a.sequence(1)))/(t(end)-t(1)),...
 'attitude_stream_rate_Hz',(height(a)-1)/(t(end)-t(1)),...
 'attitude_records_not_in_stream',sum(max(0,diff(double(a.sequence))-1)),...
 'compute_us_percentiles',prctile(a.compute_us,[0 50 99 100]),...
 'free_compute_us_percentiles',prctile(a.compute_us(mask),[0 50 99 100]),...
 'native_interval_us_percentiles',prctile(native_dt,[0 50 99 100]),...
 'min_stack_high_water',min(a.stack_high_water),'max_quaternion_norm_error',max(norm_error),...
 'minimum_covariance_diagonal',min(a{:,{'p_rx','p_ry','p_rz','p_bx','p_by','p_bz'}},[],'all'),...
 'rest_updates_while_free',max(a.rest_updates(mask))-min(a.rest_updates(mask)),...
 'crc_errors',capture.crc_errors,'selected_quaternion_kf',all(a.selected~=0),'final',capture.final);
assert(live.rest_updates_while_free==0,'Rest constraint must stay off during validation');
assert(live.max_quaternion_norm_error<1e-5 && live.minimum_covariance_diagonal>0,'Invalid embedded estimator state');
assert(live.mean_update_Hz>195,'Estimator/telemetry rate degraded');
slow=synthetic.time_s>=30 & synthetic.time_s<150;
y=[synthetic.legacy_heading synthetic.qcf_heading synthetic.kf_heading synthetic.rest_heading];
slow_result=struct('truth_turn_deg',range(synthetic.truth_heading(slow))*180/pi,...
 'estimated_turn_deg',(y(find(slow,1,'last'),:)-y(find(slow,1),:))*180/pi);
tuning=cell(1,3);sigmas=[.002 .003 .006];
for k=1:3
 label=sprintf('%.3f',sigmas(k));
 tuning{k}=struct('gravity_direction_std_rad',sigmas(k),...
  'static',jsondecode(fileread(fullfile(replays,['world_static_' label '.json']))),...
  'synthetic',jsondecode(fileread(fullfile(replays,['world_synthetic_' label '.json']))));
end
report=struct('methods',{names},'history_replay',static_report,'synthetic',synthetic_report,'slow_turn',slow_result,'live',live,'noise_parameter_screen',{tuning},...
 'parameters',struct('rotation_error_frame','world','gyro_sample_std_rad_s',.00070,'gravity_direction_std_rad',.003,...
 'gyro_bias_random_walk_rad_s_sqrt_s',5e-6,'gravity_nis_limit',9.21,'relative_acc_norm_gate',.08),...
 'scope',['Six-axis quaternion error-state KF; no magnetometer and no absolute heading observation. '...
 'Gravity correction preserves unobservable heading and along-gravity gyro bias. '...
 'Known fixed-stand rest is an explicit external condition for 30s only, never an automatic slow-turn gate. '...
 'Live data assumes the stand held still; no independent orientation reference or ground balance test. '...
 'Synthetic mixed-axis truth and slow turns test representation/numerics, not motor closed-loop superiority.']);
fid=fopen(fullfile(out,'report.json'),'w');fprintf(fid,'%s',jsonencode(report,PrettyPrint=true));fclose(fid);
fig=figure('Visible','off','Position',[100 100 1500 950]);tiledlayout(2,2,'TileSpacing','compact');
nexttile;v=[static.legacy_heading static.qcf_heading static.kf_heading static.rest_heading];
ref=interp1(static.time_s,v,30);plot(static.time_s,v*180/pi-ref*180/pi);xline(30,'k--');grid on;
xlabel('时间 (s)');ylabel('相对30秒时的航向 (°)');title('历史10分钟实测回放：不能只靠重力去掉yaw漂移');legend(names,'Location','southwest');
nexttile;plot(t,h0,t,h1);xline(t(first),'k--');grid on;xlabel('时间 (s)');ylabel('自由积分航向变化 (°)');
title('新台架实测：学习后关掉静止约束');legend('原欧拉互补','四元数KF＋已学偏置');
nexttile;plot(synthetic.time_s(slow),y(slow,:)*180/pi);hold on;
plot(synthetic.time_s(slow),synthetic.truth_heading(slow)*180/pi,'k--','LineWidth',1.5);grid on;
xlabel('时间 (s)');ylabel('相对航向 (°)');title('合成0.02°/s慢转：静止约束关闭后不能吞掉转向');legend([names {'真值'}],'Location','northwest');
nexttile;plot(synthetic.time_s,synthetic.kf_orientation_error*180/pi,synthetic.time_s,synthetic.rest_orientation_error*180/pi);grid on;
xlabel('时间 (s)');ylabel('四元数姿态误差角 (°)');title('合成耦合三轴、大倾角、加速干扰：全姿态误差');legend('仅重力KF','有初始静止偏置学习的KF');
sgtitle('四元数＋偏置KF：历史回放、新静止实测、三轴真值仿真分别比较');
exportgraphics(fig,fullfile(out,'comparison.png'),'Resolution',160);close(fig);
disp(live);disp(slow_result);
end
