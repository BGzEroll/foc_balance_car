function stats=analyze_lqi_data
here=fileparts(mfilename('fullpath'));f=fullfile(here,'data','samples.csv');
T=readtable(f,'VariableNamingRule','preserve');
valid=T.mode==2&bitand(uint32(T.flags),uint32(7))==7&T.fault==0&...
 T.imu_age_us<=20000&T.encoder_age_us<=1500&T.current_age_a_us<1000&T.current_age_b_us<1000;
[present,prior]=ismember(T.cycle-1,T.cycle);valid=valid&present;
idx=find(valid);errors=[T.iq_a(idx)+T.command_a(prior(idx)),T.iq_b(idx)-T.command_b(prior(idx))];
V=T(idx,:);q=V.pitch_rate-movmean(V.pitch_rate,9);a=V.pitch-movmean(V.pitch,9);
stats=struct('samples',height(T),'valid_samples',numel(idx),'sample_period_s',median(diff(T.sample_us))/1e6,...
 'missing_cycles',sum(max(0,diff(T.cycle)-1)),'measured_limit_A',unique(V.current_limit_A)',...
 'current_tracking_rms_A',sqrt(mean(errors.^2)), 'pitch_highpass_std_rad',std(a),...
 'rate_highpass_std_rad_s',std(q),'pitch_mean_deg',rad2deg(mean(V.pitch)),...
 'pitch_std_deg',rad2deg(std(V.pitch)),'bus_range_V',[min(V.bus) max(V.bus)],...
 'caveat','High-pass residual includes real motion. Used only as a stress amplitude, not an identified IMU noise/bias. Tracking uses previous-cycle commands; it is not a physical 5ms actuator-delay measurement. Rejected empirical plants remain excluded.');
if ~isfolder(fullfile(here,'results')),mkdir(fullfile(here,'results'));end
fid=fopen(fullfile(here,'results','measured_constraints.json'),'w');fprintf(fid,'%s',jsonencode(stats,PrettyPrint=true));fclose(fid);
end
